#!/usr/bin/env node
// Writes supabase/seeds/ref/cities.sql from the GeoNames dump cities15000.txt (cities of 15 000 people or more, CC BY 4.0,
// https://download.geonames.org/export/dump/). The dump changes daily, so CI does not regenerate this seed as it does the
// others of scripts/gen-ref-seeds.mjs: download the dump, run
//   node scripts/gen-city-seed.mjs <path of cities15000.txt> [download date YYYY-MM-DD]
// and commit the output. Only cities of a country in supabase/seeds/ref/countries.sql are kept, and a name is kept once
// per country (the most populous city of that name), so a suggestion list never shows the same name twice.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const OUT_DIR = new URL('../supabase/seeds/ref/', import.meta.url)
const ROWS_PER_INSERT = 2000

const [source, downloaded = new Date().toISOString().slice(0, 10)] = process.argv.slice(2)
if (!source || !/^\d{4}-\d{2}-\d{2}$/.test(downloaded)) {
  process.stderr.write('Usage: node scripts/gen-city-seed.mjs <path of cities15000.txt> [download date YYYY-MM-DD]\n')
  process.exit(2)
}

const countryCodes = new Set(
  [...readFileSync(fileURLToPath(new URL('countries.sql', OUT_DIR)), 'utf8').matchAll(/^ {2}\('([A-Z]{2})',/gm)].map((match) => match[1]),
)
if (countryCodes.size < 249) throw new Error(`expected at least 249 countries in countries.sql, got ${countryCodes.size}`)

// The key of a name within its country: case and accents ignored, as private.fold_text does in the database.
const nameKey = (name) => name.normalize('NFD').replace(/\p{M}/gu, '').toLowerCase()

const kept = new Map()
for (const line of readFileSync(source, 'utf8').split('\n')) {
  if (line === '') continue
  const fields = line.split('\t')
  const id = Number(fields[0])
  const name = fields[1].trim()
  const country = fields[8]
  const population = Number(fields[14]) || 0
  if (!Number.isInteger(id) || !countryCodes.has(country) || name.length === 0 || name.length > 100) continue
  const key = `${country}|${nameKey(name)}`
  const other = kept.get(key)
  if (!other || population > other.population || (population === other.population && id < other.id)) {
    kept.set(key, { id, country, name, population })
  }
}

const cities = [...kept.values()].sort((a, b) => a.id - b.id)
if (cities.length < 20000) throw new Error(`expected at least 20000 cities, got ${cities.length}`)

const quote = (text) => `'${text.replaceAll("'", "''")}'`
const inserts = []
for (let start = 0; start < cities.length; start += ROWS_PER_INSERT) {
  const values = cities
    .slice(start, start + ROWS_PER_INSERT)
    .map(({ id, country, name, population }) => `  (${id}, ${quote(country)}, ${quote(name)}, ${population})`)
    .join(',\n')
  inserts.push(
    `insert into public.cities (id, country_code, name, population) values\n${values}\non conflict (id) do update set country_code = excluded.country_code, name = excluded.name, population = excluded.population;\n`,
  )
}

const header =
  `-- Cities of 15 000 people or more from GeoNames cities15000 (https://www.geonames.org, CC BY 4.0), downloaded ${downloaded}.\n` +
  '-- Generated by scripts/gen-city-seed.mjs; do not edit by hand.\n'
writeFileSync(fileURLToPath(new URL('cities.sql', OUT_DIR)), `${header}\n${inserts.join('\n')}`)
process.stdout.write(`supabase/seeds/ref/cities.sql: ${cities.length} cities\n`)
